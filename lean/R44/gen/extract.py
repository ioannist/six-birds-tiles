#!/usr/bin/env python3
"""Generate Lean literals for the R44 finite core from canonical evidence only.

This script deliberately does not import anything from verify/packets.  Apart
from translating JSON/CSV records, its only derived inventory is the list of
complete-feature mate poses, obtained directly from the panel table by the
definition in ALIGNMENT_PROOF.md section 5.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import itertools
import json
from fractions import Fraction
from pathlib import Path


HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent
REPO = PROJECT.parents[1]

INPUTS = (
    REPO / "solid/native_panels.csv",
    REPO / "solid/r44_solid.json",
    REPO / "certificates/candidate_certificate.json",
    REPO / "certificates/companion_collision_certificate.json",
)
OUTPUTS = (
    PROJECT / "R44/Generated/CoreData.lean",
    PROJECT / "R44/Generated/MateData.lean",
)
MANIFEST = HERE / "GENERATED.sha256"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def lean_int(n: int) -> str:
    return str(n) if n >= 0 else f"({n})"


def v3(v) -> str:
    a, b, c = map(int, v)
    return f"v {lean_int(a)} {lean_int(b)} {lean_int(c)}"


def frame(g) -> str:
    p, s = g
    return (
        f"fr {int(p[0])} {int(p[1])} {int(p[2])} "
        f"{lean_int(int(s[0]))} {lean_int(int(s[1]))} {lean_int(int(s[2]))}"
    )


def pose(x) -> str:
    g, t = x
    return f"po ({frame(g)}) ({v3(t)})"


def pose_numbers(x):
    (p, s), t = x
    return tuple(map(int, (*p, *s, *t)))


def encode_rows(rows):
    return "\n".join(",".join(map(str, row)) for row in rows)


def encoded_pose_list(poses):
    return f"decodePoses {json.dumps(encode_rows(map(pose_numbers, poses)))}"


def lean_list(items, indent="  ") -> str:
    items = list(items)
    if not items:
        return "[]"
    return "[\n" + ",\n".join(indent + x for x in items) + "\n]"


def header(inputs: dict[str, str]) -> str:
    receipts = "\n".join(f"--   {digest}  {name}" for name, digest in inputs.items())
    return f"""-- GENERATED by gen/extract.py. DO NOT EDIT.
-- Canonical inputs:
{receipts}

"""


def parse_panels(path: Path):
    rows = []
    with path.open(newline="") as f:
        for r in csv.DictReader(f):
            centres = [Fraction(r[f"center_{a}"]) for a in "xyz"]
            centre2 = []
            for q in centres:
                q2 = 2 * q
                if q2.denominator != 1:
                    raise ValueError("panel centre is not half-integral")
                centre2.append(q2.numerator)
            coeffs = [int(r[f"a_{i}"]) for i in range(8)]
            rows.append(
                {
                    "panel": int(r["panel"]),
                    "axis": int(r["normal_axis"]),
                    "sign": int(r["outward_sign"]),
                    "center2": tuple(centre2),
                    "coeffs": tuple(coeffs),
                }
            )
    if [p["panel"] for p in rows] != list(range(24)):
        raise ValueError("panel numbering is not canonical 0..23")
    return rows


def permutations_and_signs():
    return tuple(
        (p, s)
        for p in itertools.permutations(range(3))
        for s in itertools.product((-1, 1), repeat=3)
    )


def act(g, x):
    p, s = g
    return tuple(s[i] * x[p[i]] for i in range(3))


def sub(a, b):
    return tuple(x - y for x, y in zip(a, b))


def native_features(panels):
    offsets = ((-1, -2), (-1, 2), (1, -2), (1, 2),
               (-2, -1), (-2, 1), (2, -1), (2, 1))
    answer = []
    for panel in panels:
        axis = panel["axis"]
        tangent = [i for i in range(3) if i != axis]
        for slot, offset in enumerate(offsets):
            center8 = [4 * q for q in panel["center2"]]
            center8[tangent[0]] += offset[0]
            center8[tangent[1]] += offset[1]
            normal = [0, 0, 0]
            normal[axis] = panel["sign"]
            answer.append(
                (8 * panel["panel"] + slot, tuple(center8), tuple(normal), panel["coeffs"][slot])
            )
    return tuple(answer)


def complete_feature_mates(features):
    mates = {}
    for g in permutations_and_signs():
        moved = [(act(g, c), act(g, n), h) for _, c, n, h in features]
        for role, c, n, h in features:
            opposite = tuple(-z for z in n)
            for d, m, k in moved:
                if m == opposite and k == -h:
                    p = (g, sub(c, d))
                    mates.setdefault(p, set()).add(role)
    return [(p, sorted(roles)) for p, roles in sorted(mates.items())]


def make_core(inputs, panels, solid, candidate):
    panel_rows = []
    for p in panels:
        coeffs = lean_list((lean_int(x) for x in p["coeffs"]), "      ")
        panel_rows.append(
            f"{{ axis := {p['axis']}, outward := {lean_int(p['sign'])}, "
            f"center2 := {v3(p['center2'])}, coefficients := {coeffs} }}"
        )

    components = []
    for comp in candidate["balanced_components"]:
        signs = sorted((int(k), int(v)) for k, v in comp["signs"].items())
        pairs = lean_list((f"({u}, {lean_int(s)})" for u, s in signs), "      ")
        components.append(pairs)

    central = []
    for sid, required_mask, existing_mask, viable in candidate["central_completion"]:
        central.append(
            "{ shellId := %d, requiredMask := %d, existingMask := %d, viable := %s }"
            % (sid, required_mask, existing_mask, lean_list(map(str, viable), "      "))
        )

    data = {
        "children": lean_list(map(pose, candidate["children"])),
        "solidChildren": lean_list(map(pose, solid["substitution_children"])),
        "panels": lean_list(panel_rows),
        "panelProfile": lean_list(lean_int(x) for p in panels for x in p["coeffs"]),
        "solidProfile": lean_list(map(lean_int, solid["profile"])),
        "certificateProfile": lean_list(map(lean_int, candidate["profile"])),
        "closureCounts": lean_list(map(str, candidate["closure_counts"])),
        "contactStates": lean_list(map(pose, candidate["contact_states"])),
        "signedRows": lean_list(
            f"{{ left := {a}, right := {b}, sign := {lean_int(s)} }}"
            for a, b, s in candidate["signed_rows"]
        ),
        "balancedComponents": lean_list(components),
        "rawContacts": encoded_pose_list(candidate["raw_contacts"]),
        "legalContacts": lean_list(map(pose, candidate["legal_contacts"])),
        "shellCells": lean_list(map(v3, candidate["shell_cells"])),
        "wholeBodyConflicts": lean_list(map(str, candidate["whole_body_conflicts"])),
        "shellSolutions": lean_list(
            lean_list(map(str, solution), "      ") for solution in candidate["solutions"]
        ),
        "parents": lean_list(
            lean_list(map(pose, parent), "      ") for parent in candidate["parents"]
        ),
        "roleOptions": lean_list(
            lean_list(map(str, roles), "      ") for roles in candidate["role_options"]
        ),
        "centralCompletion": lean_list(central),
        "centralPassed": lean_list(map(str, candidate["central_passed"])),
        "centralDead": lean_list(map(str, candidate["central_dead"])),
        "centralWrong": lean_list(map(str, candidate["central_wrong"])),
        "macroCandidates": encoded_pose_list(candidate["macro_candidates"]),
        "macroNonoverlap": str(candidate["macro_nonoverlap"]),
        "macroLegal": lean_list(map(pose, candidate["macro_legal"])),
        "nativeSymmetries": lean_list(
            f"n3 {p[0]} {p[1]} {p[2]}" for p in candidate["native_symmetries"]
        ),
        "orientationGroup": lean_list(frame(g) for g in candidate["orientation_group"]),
    }
    decls = []
    types = {
        "children": "List Pose", "solidChildren": "List Pose", "panels": "List Panel",
        "panelProfile": "List Int", "solidProfile": "List Int", "certificateProfile": "List Int",
        "closureCounts": "List Nat", "contactStates": "List Pose", "signedRows": "List SignEquation",
        "balancedComponents": "List (List (Nat × Int))", "rawContacts": "List Pose",
        "legalContacts": "List Pose", "shellCells": "List V3", "wholeBodyConflicts": "List Nat",
        "shellSolutions": "List (List Nat)", "parents": "List (List Pose)",
        "roleOptions": "List (List Nat)", "centralCompletion": "List CentralRecord",
        "centralPassed": "List Nat", "centralDead": "List Nat", "centralWrong": "List Nat",
        "macroCandidates": "List Pose", "macroNonoverlap": "Nat", "macroLegal": "List Pose",
        "nativeSymmetries": "List N3",
        "orientationGroup": "List Frame",
    }
    for name, value in data.items():
        decls.append(f"def {name} : {types[name]} := {value}")
    vertices10000 = []
    for point in solid["vertices"]:
        scaled = []
        for coordinate in point:
            q = Fraction(coordinate) * 10000
            if q.denominator != 1:
                raise ValueError("mesh coordinate is not in (1/10000)Z")
            scaled.append(q.numerator)
        vertices10000.append(tuple(scaled))
    summary = f"""
def solidVertexCount : Nat := {solid['vertex_count']}
def solidEdgeCount : Nat := {solid['edge_count']}
def solidTriangleCount : Nat := {solid['triangle_count']}
def solidExactVolume : String := {json.dumps(solid['exact_volume'])}

def solidVertices10000 : List V3 := decodeV3s {json.dumps(encode_rows(vertices10000))}

def solidTriangles : List N3 := decodeN3s {json.dumps(encode_rows(solid['triangles']))}
"""
    return header(inputs) + "import R44.Types\n\nnamespace R44.Generated\n\n" + "\n\n".join(decls) + summary + "\nend R44.Generated\n"


def make_mates(inputs, mates, witnesses):
    role_encoded = encode_rows((*pose_numbers(p), *roles) for p, roles in mates)
    witness_encoded = encode_rows(
        (*pose_numbers(w["rejected_pose"]), w["marker_owner"], w["native_role"], w["possible_partners"])
        for w in witnesses
    )
    return header(inputs) + f"""import R44.Types

namespace R44.Generated

def mateRecords : List MateRecord := decodeMateRecords {json.dumps(role_encoded)}

def matePoses : List Pose := mateRecords.map MateRecord.pose

def rejectionWitnesses : List RejectionWitness := decodeRejectionWitnesses {json.dumps(witness_encoded)}

end R44.Generated
"""


def render_all():
    input_hashes = {str(p.relative_to(REPO)): sha256(p) for p in INPUTS}
    panels = parse_panels(INPUTS[0])
    solid = json.loads(INPUTS[1].read_text())
    candidate = json.loads(INPUTS[2].read_text())
    collision = json.loads(INPUTS[3].read_text())
    if candidate["children"] != solid["substitution_children"]:
        raise ValueError("candidate/solid child literals disagree")
    if candidate["profile"] != solid["profile"]:
        raise ValueError("candidate/solid profiles disagree")
    if [x for p in panels for x in p["coeffs"]] != solid["profile"]:
        raise ValueError("panel/solid profiles disagree")
    mates = complete_feature_mates(native_features(panels))
    if len(mates) != 6862:
        raise ValueError(f"derived {len(mates)} mate poses, expected 6862")
    if len(collision["witnesses"]) != 5273:
        raise ValueError("unexpected rejection witness count")
    return input_hashes, {
        OUTPUTS[0]: make_core(input_hashes, panels, solid, candidate),
        OUTPUTS[1]: make_mates(input_hashes, mates, collision["witnesses"]),
    }


def manifest_text(input_hashes, rendered):
    lines = ["# sha256  path", "# canonical inputs"]
    lines.extend(f"{digest}  ../../../{name}" for name, digest in input_hashes.items())
    lines.append("# generated Lean sources")
    for path, text in rendered.items():
        digest = hashlib.sha256(text.encode()).hexdigest()
        lines.append(f"{digest}  ../{path.relative_to(PROJECT)}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="verify checked-in generated files and manifest")
    args = parser.parse_args()
    input_hashes, rendered = render_all()
    expected_manifest = manifest_text(input_hashes, rendered)
    if args.check:
        bad = []
        for path, text in rendered.items():
            if not path.exists() or path.read_text() != text:
                bad.append(str(path.relative_to(PROJECT)))
        if not MANIFEST.exists() or MANIFEST.read_text() != expected_manifest:
            bad.append(str(MANIFEST.relative_to(PROJECT)))
        if bad:
            raise SystemExit("generated-file mismatch: " + ", ".join(bad))
        print("generated literals and SHA256 manifest: PASS")
        return
    for path, text in rendered.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    MANIFEST.write_text(expected_manifest)
    print(f"wrote {len(rendered)} Lean files and {MANIFEST.relative_to(PROJECT)}")


if __name__ == "__main__":
    main()
